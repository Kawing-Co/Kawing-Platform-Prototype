import {test,expect} from '@playwright/test';
const rail=page=>page.getByRole('region',{name:'Interactive walkthrough'});
const next=page=>rail(page).getByRole('button',{name:'Continue',exact:true}).click();
const fits=page=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1);
test('partner completes the eight-step story with one shared order and an offline replay',async({page})=>{
 await page.goto('/?workspace=merchant#Start%20here');
 await expect(page.getByRole('heading',{name:'One order. A whole business, connected.'})).toBeVisible();
 await page.getByRole('button',{name:'Start guided demo',exact:false}).click();
 await expect(rail(page)).toContainText('STEP 1 OF 8');
 await expect(rail(page).getByRole('button',{name:'Continue',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:'Add Harvest bowl',exact:true}).click();
 await page.getByRole('button',{name:'Review your order',exact:true}).click();
 await page.getByRole('button',{name:'Place demo order',exact:true}).click();
 await page.getByRole('button',{name:'I’ve sent the demo payment'}).click();
 await expect(rail(page)).toContainText('Ready for the next step');
 await next(page);
 const card=page.locator('.kitchen-card.guide-highlight');
 await expect(card).toHaveCount(1);
 await card.getByRole('button',{name:'Review payment',exact:true}).click();
 await card.getByRole('button',{name:'Confirm payment',exact:true}).click();
 await card.getByRole('button',{name:'Start preparing'}).click();
 await card.getByRole('button',{name:'Mark ready'}).click();
 await card.getByRole('button',{name:'Mark served'}).click();
 await next(page);
 await expect(page.locator('.stat-card').first()).toContainText('13,125');
 await next(page);
 await page.getByLabel('Restaurant name',{exact:true}).fill('Salo & Friends');
 await page.getByRole('button',{name:'Save design',exact:true}).first().click();
 await next(page);
 await page.getByRole('button',{name:'Toggle availability for Salo garden salad'}).click();
 await next(page);
 await page.getByLabel('Analytics period').selectOption('This week');
 await next(page);
 await expect(rail(page)).toContainText('STEP 7 OF 8');
 await page.getByRole('button',{name:'Enable offline simulation',exact:true}).click();
 await page.getByRole('button',{name:'Create an offline demo order'}).click();
 await page.getByRole('button',{name:'Order now',exact:true}).click();
 await page.getByRole('button',{name:'Add Harvest bowl',exact:true}).click();
 await page.getByRole('button',{name:'Review your order',exact:true}).click();
 await page.getByRole('button',{name:'Save order offline',exact:true}).click();
 await expect(rail(page).getByRole('button',{name:'Continue',exact:true})).toBeDisabled();
 await page.getByRole('button',{name:'Reconnect',exact:true}).click();
 await next(page);
 await expect(rail(page)).toContainText('STEP 8 OF 8');
 await rail(page).getByRole('button',{name:'Finish walkthrough'}).click();
 await expect(page.getByRole('heading',{name:'That’s Kawing. One business, working together.'})).toBeVisible();
 const orders=await page.evaluate(()=>JSON.parse(localStorage.getItem('kawing-demo-v1')).orders.filter(o=>!o.seed));
 expect(orders).toHaveLength(2);expect(orders.some(o=>o.status==='served')).toBe(true);expect(orders.some(o=>o.status==='new')).toBe(true);
 await page.getByRole('button',{name:'Explore the feature map'}).click();
 await expect(page.getByRole('heading',{name:'Your map to Kawing'})).toBeVisible();
});
test('mobile guide pauses, resumes, skips, and preserves progress across refresh and browser history',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto('/?workspace=merchant#Start%20here');
 expect(await fits(page)).toBe(true);
 await page.getByRole('button',{name:'Start guided demo',exact:false}).click();
 expect(await fits(page)).toBe(true);
 await rail(page).getByRole('button',{name:'Skip step'}).click();
 await expect(rail(page)).toContainText('STEP 2 OF 8');
 await rail(page).getByRole('button',{name:'Pause guided demo'}).click();
 await expect(rail(page)).not.toBeVisible();
 await page.getByRole('button',{name:'Demo home',exact:true}).click();
 await page.reload();
 await page.getByRole('button',{name:'Resume guided demo',exact:false}).click();
 await expect(rail(page)).toContainText('STEP 2 OF 8');
 await expect(page).toHaveURL(/#Orders$/);
 expect(await fits(page)).toBe(true);
 await rail(page).getByRole('button',{name:'Back',exact:true}).click();
 await expect(rail(page)).toContainText('STEP 1 OF 8');
 await rail(page).getByRole('button',{name:'Pause guided demo'}).click();
 await page.getByRole('button',{name:'Demo home',exact:true}).click();
 await page.locator('.feature-map').getByRole('button',{name:/Make the Business Profile yours/}).click();
 await expect(page).toHaveURL(/#Storefront$/);
 await page.reload();
 await expect(page.getByLabel('Restaurant name',{exact:true})).toBeVisible();
 expect(await fits(page)).toBe(true);
 await page.goBack();
 await expect(page.getByRole('heading',{name:'Your map to Kawing'})).toBeVisible();
});

