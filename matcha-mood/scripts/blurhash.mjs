// Computes BlurHash strings for every photo in media/photo from a 32×40 RGB thumbnail
// (`npm run blurhash` after regenerating photography). Output: data/blurhashes.js
import { readFileSync, writeFileSync } from "node:fs";
import { encode } from "../js/lib/blurhash.js";
const src = process.argv[2];
const tiny = JSON.parse(readFileSync(src, "utf8"));
const out = {};
for (const [name, m] of Object.entries(tiny)) {
  const rgba = new Uint8ClampedArray(32 * 40 * 4);
  for (let i = 0, j = 0; i < m.px.length; i += 3, j += 4) { rgba[j] = m.px[i]; rgba[j + 1] = m.px[i + 1]; rgba[j + 2] = m.px[i + 2]; rgba[j + 3] = 255; }
  out[name] = encode(rgba, 32, 40, 4, 5);
}
writeFileSync(new URL("../data/blurhashes.js", import.meta.url), "// Generated by scripts/blurhash.mjs from the real photographs.\nexport default " + JSON.stringify(out, null, 1) + ";\n");
console.log(Object.keys(out).length, "hashes");
